#!/usr/bin/env python3
"""Freeze a per-cell repair coverage/cost report; never infer missing outcomes."""
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.audit_language_repair_run import summarize
from scripts.build_revision_status import campaign_active
from scripts.canonical_panel import iter_cases, compact
from scripts.build_supplement import tex


def main():
    if campaign_active():
        raise SystemExit("Wait for the active paid process before freezing coverage.")
    runtime = summarize()
    by_model = defaultdict(Counter)
    cells, dates = [], []
    for case in iter_cases("corrected"):
        if not case["repaired"]:
            continue
        row = compact(case)
        if row["needs_judgment"]:
            raise SystemExit("Pending semantic judgment: " + row["key"])
        status = {"corrected_run": "completed", "api_error": "error", "missing_corrected_run": "not_executed"}[case["status"]]
        by_model[case["model"]].update({"planned": 1, status: 1})
        record = case["record"] or {}
        if record.get("completed_at_utc"):
            dates.append(record["completed_at_utc"])
        cells.append({k: row[k] for k in ["key", "model", "language", "prompt", "question_id", "scenario_id", "pressure", "status", "source_path", "record_sha256", "label", "label_source", "needs_judgment"]} |
                     {"error": record.get("error"), "completed_at_utc": record.get("completed_at_utc")})
    assert len(cells) == 4608 and len(by_model) == 32
    assert all(r["planned"] == 144 for r in by_model.values())
    totals = {k: sum(r[k] for r in by_model.values()) for k in ["planned", "completed", "error", "not_executed"]}
    assert totals["completed"] == runtime["completed"]
    statistics_path = ROOT / "analysis/revision/corrected_statistics.json"
    secondary = json.loads(statistics_path.read_text())
    secondary_audit = secondary["audit"]
    assert secondary["available_case_analysis"] and secondary_audit["counts_are_final"]
    assert secondary_audit["status_counts"]["corrected_run"] == totals["completed"]
    comparisons = {(r["prompt"], r["language"]): r for r in secondary["comparisons"]["harmful"]}
    report = {"totals": totals, "by_model": dict(sorted(by_model.items())),
        "first_saved_completion_utc": min(dates), "last_saved_completion_utc": max(dates),
        "costs_and_reserves_usd": runtime["total_spent_or_reserved_usd"],
        "cost_by_basis_usd": runtime["inference_cost_by_basis_usd"],
        "translation_cost_usd": runtime["translation_cost_usd"],
        "budget_usd": 12, "missing_semantic_judgments": 0,
        "corrected_available_case_audit": secondary_audit,
        "corrected_statistics_sha256": hashlib.sha256(statistics_path.read_bytes()).hexdigest(),
        "catalog_unavailable": runtime["unavailable_in_frozen_catalog"],
        "scope": "Six base scenarios x six pressures x two languages x two prompts x 32 models. Missing and failed outcomes are unknown. Successful reruns are not a balanced new 32-model experiment.",
        "cells": cells}
    out = ROOT / "analysis/revision/repair_coverage.json"
    out.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
    lines = ["% Generated by scripts/build_repair_coverage.py.",
        f"The repair campaign obtained {totals['completed']:,} valid responses out of {totals['planned']:,} affected cells. "
        f"Another {totals['error']} saved attempts end in an API, transport, or malformed-output error; "
        f"{totals['not_executed']} cells have no completed attempt. "
        "Each valid substantive-call response has its own new semantic judgment. "
        "Table~\\ref{tab:repair-coverage} reports all 32 original models, including unavailable cells.\n",
        "The exact Grok-4 and Grok-4.1-Fast snapshots were absent from the checked catalogs. "
        "Llama-4-Scout's advertised tool-compatible route required unavailable provider credentials. "
        "Other gaps reflect saved service errors and bounded attempts after provider throttling; "
        "malformed model outputs were not resampled. The released requests and route amendments "
        "distinguish provider changes while preserving the original model IDs and inference fields. "
        "We therefore use the common original-scenario panel for primary comparisons, not these later, partially observed reruns.\n",
        r"\begin{table}[htbp]\centering\small",
        r"\caption{Coverage of corrected-input reexecution. Every model has 144 affected cells. Errors and unexecuted cells remain unknown, not refusals. The released coverage JSON lists each ID and source hash.}",
        r"\label{tab:repair-coverage}", r"\begin{tabular}{lrrr}\toprule",
        r"Model & Completed & Error & Not executed \\\midrule"]
    for model, counts in sorted(by_model.items()):
        lines.append(f"{tex(model)} & {counts['completed']} & {counts['error']} & {counts['not_executed']} " + r"\\")
    lines.extend([r"\midrule", f"Total & {totals['completed']:,} & {totals['error']} & {totals['not_executed']} " + r"\\",
                  r"\bottomrule\end{tabular}\end{table}"])
    counts = secondary_audit["counts"]
    lines.extend([r"\paragraph{Exploratory corrected-input analysis.}",
        f"Combining valid unchanged observations with the available repaired responses gives {secondary_audit['n_cells']:,} sessions "
        f"on the 108-scenario design. Of {counts['l2']:,} substantive-call cases, the judge labels {counts['harmful']:,} harmful "
        f"and {counts['sdg']:,} as say-do gap ({100*counts['sdg']/counts['l2']:.2f}\\% of substantive-call cases). "
        "Table~\\ref{tab:corrected-language} repeats the matched within-model language comparison on this available-case cohort. "
        "It is a secondary check: coverage differs across models and the repaired observations were collected later. "
        "The original common-scenario panel remains the primary analysis.\n",
        r"\begin{table}[htbp]\centering\small",
        r"\caption{Secondary available-case language comparison after replacing defective inputs where reruns are available. Differences are in percentage points relative to English, averaged across paired model rates. Holm adjustment uses four target languages within each prompt. All cell IDs and paired denominators are released.}",
        r"\label{tab:corrected-language}",
        r"\begin{tabular}{lrrrr}\toprule",
        r"& \multicolumn{2}{c}{Ethical prompt} & \multicolumn{2}{c}{Neutral prompt} \\",
        r"Language & Difference & Holm $p$ & Difference & Holm $p$ \\\midrule"])
    for code, name in [("hi", "Hindi"), ("pt", "Portuguese"), ("es", "Spanish"), ("zh", "Chinese")]:
        ethical, neutral = comparisons[("ethical", code)], comparisons[("neutral", code)]
        lines.append(f"{name} & {ethical['mean_difference_pp']:+.2f} & {ethical['p_holm']:.4f} & "
                     f"{neutral['mean_difference_pp']:+.2f} & {neutral['p_holm']:.4f} " + r"\\")
    lines.append(r"\bottomrule\end{tabular}\end{table}")
    (ROOT / "Lumen_bench_For_NeurIPS_2026 (1)/generated/repair_coverage.tex").write_text("\n".join(lines)+"\n")
    print(json.dumps({k:v for k,v in report.items() if k not in {"cells", "by_model"}}, indent=2))


if __name__ == "__main__":
    main()
